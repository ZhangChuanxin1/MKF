func TestGuardedCompactP2GIngressAndOnlineContract(t *testing.T) {
	params, err := CKKSParameters(guardedCompactP2GParameterID)
	if err != nil {
		t.Fatal(err)
	}
	kgen := ckks.NewKeyGenerator(params)
	shares := make([]*rlwe.SecretKey, fullResNet20Parties)
	public := make([]*rlwe.PublicKey, fullResNet20Parties)
	for party := range shares {
		shares[party], public[party] = kgen.GenKeyPair()
	}
	aggregate := aggregateSecret(params.Parameters, shares)
	crs, err := utils.NewPRNG()
	if err != nil {
		t.Fatal(err)
	}
	foldMaterial, err := generateDistributedPublicFoldKeys(params, shares, crs)
	if err != nil {
		t.Fatal(err)
	}
	evaluationCRS, err := utils.NewPRNG()
	if err != nil {
		t.Fatal(err)
	}
	evaluationKey, err := generateCollectiveEvaluationKey(params, shares, []int{1}, evaluationCRS)
	if err != nil {
		t.Fatal(err)
	}
	adapter, err := newGuardedCompactMKFLattigoAdapter(params, evaluationKey, foldMaterial.FoldKeys, len(shares))
	if err != nil {
		t.Fatal(err)
	}
	encoder := ckks.NewEncoder(params)
	left, err := adapter.ownerCarrier(encoder, public, 0, []complex128{0.125, -0.25, 0.375})
	if err != nil {
		t.Fatal(err)
	}
	right, err := adapter.ownerCarrier(encoder, public, 1, []complex128{0.5, 0.25, -0.125})
	if err != nil {
		t.Fatal(err)
	}
	product := adapter.MulRelinNew(left, right)
	if err := adapter.Rescale(product, params.Scale(), product); err != nil {
		t.Fatal(err)
	}
	rotated := adapter.RotateNew(product, 1)
	decoded := encoder.Decode(ckks.NewDecryptor(params, aggregate).DecryptNew(rotated), params.LogSlots())
	want := []complex128{-0.0625, -0.046875, 0}
	var maxError float64
	for index := range want {
		maxError = math.Max(maxError, cmplx.Abs(decoded[index]-want[index]))
	}
	if maxError >= 1e-5 {
		t.Fatalf("guarded compact online contract maxError=%g", maxError)
	}
	counts := adapter.snapshot()
	if counts.owners != 2 || counts.guardedFolds != 2 || counts.guardRescales != 2 || counts.networkProducts != 1 || counts.rotations != 1 || counts.polynomials != 0 || counts.refreshes != 0 {
		t.Fatalf("guarded compact contract counters=%+v", counts)
	}
	if left.Degree() != 1 || right.Degree() != 1 || product.Degree() != 1 || rotated.Degree() != 1 || left.Level() != adapter.baseMaxLevel || right.Level() != adapter.baseMaxLevel || product.Level() > adapter.baseMaxLevel || rotated.Level() > adapter.baseMaxLevel {
		t.Fatal("post-ingress ciphertext escaped permanent compact P2 domain")
	}
	t.Logf("GUARDED_COMPACT_CONTRACT_PASS construction=%s parameter=%s maxError=%.17g counts=%+v", guardedCompactMKFCKKSConstructionID, guardedCompactP2GParameterID, maxError, counts)
}

func TestGuardedCompactP2GRefreshContract(t *testing.T) {
	params, err := CKKSParameters(guardedCompactP2GParameterID)
	if err != nil {
		t.Fatal(err)
	}
	base, err := CKKSParameters("P2")
	if err != nil {
		t.Fatal(err)
	}
	kgen := ckks.NewKeyGenerator(params)
	shares := make([]*rlwe.SecretKey, fullResNet20Parties)
	public := make([]*rlwe.PublicKey, fullResNet20Parties)
	for party := range shares {
		shares[party], public[party] = kgen.GenKeyPair()
	}
	aggregate := aggregateSecret(params.Parameters, shares)
	foldCRS, err := utils.NewPRNG()
	if err != nil {
		t.Fatal(err)
	}
	foldMaterial, err := generateDistributedPublicFoldKeys(params, shares, foldCRS)
	if err != nil {
		t.Fatal(err)
	}
	adapter, err := newGuardedCompactMKFLattigoAdapter(params, rlwe.EvaluationKey{}, foldMaterial.FoldKeys, len(shares))
	if err != nil {
		t.Fatal(err)
	}
	encoder := ckks.NewEncoder(params)
	want := []complex128{0.125, -0.25, 0.375}
	input, err := adapter.ownerCarrier(encoder, public, 0, want)
	if err != nil {
		t.Fatal(err)
	}
	minLevel, logBound, ok := dckks.GetMinimumLevelForBootstrapping(128, base.Scale(), len(shares), base.Q())
	if !ok {
		t.Fatal("P2 base chain does not support the two-party refresh contract")
	}
	adapter.DropLevel(input, input.Level()-minLevel)
	crs, err := utils.NewPRNG()
	if err != nil {
		t.Fatal(err)
	}
	refreshed, err := runGuardedCompactCollectiveRefresh(params, shares, input, logBound, adapter.baseMaxLevel, crs)
	if err != nil {
		t.Fatal(err)
	}
	adapter.requireCompact("refresh contract output", refreshed)
	decoded := encoder.Decode(ckks.NewDecryptor(params, aggregate).DecryptNew(refreshed), params.LogSlots())
	var maxError float64
	for index := range want {
		maxError = math.Max(maxError, cmplx.Abs(decoded[index]-want[index]))
	}
	if maxError >= 1e-5 || refreshed.Level() != base.MaxLevel() {
		t.Fatalf("guarded compact refresh maxError=%g level=%d wantLevel=%d", maxError, refreshed.Level(), base.MaxLevel())
	}
	t.Logf("GUARDED_COMPACT_REFRESH_PASS inputLevel=%d outputLevel=%d maxError=%.17g", minLevel, refreshed.Level(), maxError)
}

