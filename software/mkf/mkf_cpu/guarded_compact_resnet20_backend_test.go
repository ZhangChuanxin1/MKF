// guardedCompactMKFLattigoAdapter implements the manuscript's canonical
// guarded compact lifecycle:
//
//	fresh sparse (n+1) at Delta*q_g -> one FoldToAggregate -> one Rescale
//	removing q_g -> permanent degree-one aggregate-domain evaluation.
//
// foldKeys are generated by the public CKG+party-PKE protocol implemented in
// distributed_public_fold_keygen_test.go. Relinearization and rotation keys
// used after ingress are generated by generateCollectiveEvaluationKey. None
// of these protocols forms the aggregate secret. The aggregate secret retained
// by the executor is reconstructed only after key generation as a test-only
// decryption oracle and is not online evaluation material.
type guardedCompactMKFLattigoAdapter struct {
	ckks.Evaluator
	parameterID  string
	params       ckks.Parameters
	guardPrime   uint64
	foldKeys     []*rlwe.SwitchingKey
	switcher     *switchWorkspace
	baseMaxLevel int
	profile      Profile
	counts       guardedCompactMKFCounts
	setup        guardedCompactSetupEvidence
}

func makeGuardedCompactSetupEvidence(foldMaterial *distributedPublicFoldKeyMaterial, evaluationKey rlwe.EvaluationKey) (guardedCompactSetupEvidence, error) {
	if foldMaterial == nil {
		return guardedCompactSetupEvidence{}, fmt.Errorf("nil distributed fold-key material")
	}
	var relinearizationBytes, rotationBytes int
	if evaluationKey.Rlk != nil {
		encoded, err := evaluationKey.Rlk.MarshalBinary()
		if err != nil {
			return guardedCompactSetupEvidence{}, fmt.Errorf("marshal collective relinearization key: %w", err)
		}
		relinearizationBytes = len(encoded)
	}
	if evaluationKey.Rtks != nil {
		encoded, err := evaluationKey.Rtks.MarshalBinary()
		if err != nil {
			return guardedCompactSetupEvidence{}, fmt.Errorf("marshal collective rotation-key set: %w", err)
		}
		rotationBytes = len(encoded)
	}
	transcript := foldMaterial.Transcript
	ckgShareBytes := 0
	for _, size := range transcript.CKGShareBytes {
		ckgShareBytes += size
	}
	totalEvaluation := transcript.PublishedFoldKeyBytes + relinearizationBytes + rotationBytes
	return guardedCompactSetupEvidence{
		FoldKeyGenMode: guardedCompactFoldKeyGenMode, FoldKeyConstruction: transcript.ConstructionID,
		FoldCKGRounds: transcript.CKGRounds, FoldCKGShareMessages: transcript.CKGShareMessages,
		FoldCKGShareBytes: ckgShareBytes, FoldCKGCRPBytes: transcript.CRPBytes,
		CollectivePublicKeyBytes: transcript.CollectivePublicKeyBytes,
		PublishedFoldKeyMessages: transcript.PublishedFoldKeyMessages,
		PublishedFoldKeyBytes:    transcript.PublishedFoldKeyBytes,
		RelinearizationKeyBytes:  relinearizationBytes, RotationKeySetBytes: rotationBytes,
		TotalEvaluationMaterialBytes:  totalEvaluation,
		TotalPublicSetupMaterialBytes: totalEvaluation + transcript.CollectivePublicKeyBytes,
		FoldTranscriptBytes:           transcript.TransmittedBytes, FoldTranscriptSHA256: transcript.SHA256,
	}, nil
}

func newGuardedCompactMKFLattigoAdapter(params ckks.Parameters, evaluationKey rlwe.EvaluationKey, foldKeys []*rlwe.SwitchingKey, parties int, parameterIDs ...string) (*guardedCompactMKFLattigoAdapter, error) {
	parameterID := guardedCompactP2GParameterID
	if len(parameterIDs) > 1 {
		return nil, fmt.Errorf("guarded compact adapter accepts at most one parameter ID")
	}
	if len(parameterIDs) == 1 {
		parameterID = parameterIDs[0]
	}
	profile, err := guardedCompactParameterProfileFor(parameterID)
	if err != nil {
		return nil, err
	}
	baseParams := profile.base
	if parties < 2 || len(foldKeys) != parties {
		return nil, fmt.Errorf("guarded compact adapter needs %d fold keys for %d parties", parties, parties)
	}
	if params.MaxLevel() != baseParams.MaxLevel()+1 || params.Q()[params.MaxLevel()] != profile.guardPrime || params.LogN() != profile.guarded.LogN() || params.LogSlots() != profile.guarded.LogSlots() {
		return nil, fmt.Errorf("%s guard layout mismatch: maxLevel=%d topQ=0x%x", parameterID, params.MaxLevel(), params.Q()[params.MaxLevel()])
	}
	for level, modulus := range baseParams.Q() {
		if params.Q()[level] != modulus {
			return nil, fmt.Errorf("%s base-chain mismatch at Q[%d]", parameterID, level)
		}
	}
	return &guardedCompactMKFLattigoAdapter{
		Evaluator:    ckks.NewEvaluator(params, evaluationKey),
		parameterID:  parameterID,
		params:       params,
		guardPrime:   profile.guardPrime,
		foldKeys:     foldKeys,
		switcher:     newSwitchWorkspace(params.Parameters),
		baseMaxLevel: baseParams.MaxLevel(),
	}, nil
}

func (adapter *guardedCompactMKFLattigoAdapter) requireCompact(label string, ciphertext *ckks.Ciphertext) {
	if ciphertext == nil {
		panic(fmt.Sprintf("%s received a nil ciphertext", label))
	}
	if ciphertext.Degree() != 1 {
		panic(fmt.Sprintf("%s forbids post-ingress n+1/repeated-Gamma state: degree=%d", label, ciphertext.Degree()))
	}
	if ciphertext.Level() > adapter.baseMaxLevel {
		panic(fmt.Sprintf("%s reintroduced the P2G guard level after ingress: level=%d baseMax=%d", label, ciphertext.Level(), adapter.baseMaxLevel))
	}
}

func (adapter *guardedCompactMKFLattigoAdapter) requireCompactOperand(label string, operand ckks.Operand) {
	if ciphertext, ok := operand.(*ckks.Ciphertext); ok {
		adapter.requireCompact(label, ciphertext)
	}
}

func (adapter *guardedCompactMKFLattigoAdapter) MulRelinNew(left, right ckks.Operand) *ckks.Ciphertext {
	adapter.requireCompactOperand("MulRelin(left)", left)
	adapter.requireCompactOperand("MulRelin(right)", right)
	result := adapter.Evaluator.MulRelinNew(left, right)
	adapter.requireCompact("MulRelin(output)", result)
	adapter.counts.networkProducts++
	return result
}

