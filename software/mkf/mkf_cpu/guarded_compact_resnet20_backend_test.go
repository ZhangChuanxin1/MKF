func (adapter *guardedCompactMKFLattigoAdapter) EvaluatePoly(input *ckks.Ciphertext, polynomial *ckks.Polynomial, targetScale float64) (*ckks.Ciphertext, error) {
	adapter.requireCompact("EvaluatePoly(input)", input)
	result, err := adapter.Evaluator.EvaluatePoly(input, polynomial, targetScale)
	if err != nil {
		return nil, err
	}
	adapter.requireCompact("EvaluatePoly(output)", result)
	products, countErr := kklssCarrierBSGSProductCount(polynomial)
	if countErr != nil || products != p2gn16Degree59ProductsPerActivation {
		return nil, fmt.Errorf("canonical BSGS product schedule=%d: %v", products, countErr)
	}
	adapter.counts.polynomialProducts += products
	adapter.counts.polynomials++
	return result, nil
}

// ownerCarrier is the sole n+1 boundary. It creates a fresh sparse owner
// ciphertext at Delta*q_g, folds it exactly once with a public switching key,
// and consumes q_g immediately. No n+1 object escapes this method.
func (adapter *guardedCompactMKFLattigoAdapter) ownerCarrier(encoder ckks.Encoder, public []*rlwe.PublicKey, owner int, values []complex128) (*ckks.Ciphertext, error) {
	if owner < 0 || owner >= len(public) || len(public) != len(adapter.foldKeys) {
		return nil, fmt.Errorf("guarded owner %d outside %d-party key set", owner, len(public))
	}
	level := adapter.params.MaxLevel()
	guardedScale := adapter.params.Scale() * float64(adapter.guardPrime)
	plaintext := ckks.NewPlaintext(adapter.params, level, guardedScale)
	encoder.EncodeNTT(plaintext, values, adapter.params.LogSlots())
	ciphertext := ckks.NewEncryptor(adapter.params, public[owner]).EncryptNew(plaintext)
	return adapter.foldGuardedOwnerCiphertext(ciphertext, owner)
}

// foldGuardedOwnerCiphertext is the timed half of guarded ingress. The fresh
// sparse owner encryption is created and optionally serialized before the
// timer; this method performs exactly the public FoldToAggregate and the one
// guard-prime rescale that belong to the canonical online boundary.
func (adapter *guardedCompactMKFLattigoAdapter) foldGuardedOwnerCiphertext(ciphertext *ckks.Ciphertext, owner int) (*ckks.Ciphertext, error) {
	if ciphertext == nil || ciphertext.Degree() != 1 || owner < 0 || owner >= len(adapter.foldKeys) {
		return nil, fmt.Errorf("invalid staged guarded owner ciphertext: owner=%d degree=%d parties=%d", owner, func() int {
			if ciphertext == nil {
				return -1
			}
			return ciphertext.Degree()
		}(), len(adapter.foldKeys))
	}
	level := adapter.params.MaxLevel()
	guardedScale := adapter.params.Scale() * float64(adapter.guardPrime)
	if ciphertext.Level() != level {
		return nil, fmt.Errorf("staged guarded owner level=%d, want %d", ciphertext.Level(), level)
	}
	if relative := math.Abs(ciphertext.Scale-guardedScale) / guardedScale; relative > 1e-12 {
		return nil, fmt.Errorf("staged guarded owner scale=%g, want %g", ciphertext.Scale, guardedScale)
	}
	multi := &multiCiphertext{
		C0:         ciphertext.Value[0].CopyNew(),
		Components: make([]*ring.Poly, len(adapter.foldKeys)),
		Level:      level,
		Scale:      ciphertext.Scale,
	}
	for party := range multi.Components {
		multi.Components[party] = adapter.params.RingQ().NewPolyLvl(level)
		multi.Components[party].Zero()
		multi.Components[party].IsNTT = true
	}
	multi.Components[owner].CopyValues(ciphertext.Value[1])
	multi.Components[owner].IsNTT = true
	multi.C0.IsNTT = true

	folded, err := fold(adapter.params.Parameters, multi, adapter.foldKeys, true, adapter.switcher, &adapter.profile)
	if err != nil {
		return nil, err
	}
	compact := ckks.NewCiphertextAtLevelFromPoly(level, folded)
	compact.Scale = multi.Scale
	if err := adapter.Evaluator.Rescale(compact, adapter.params.Scale(), compact); err != nil {
		return nil, fmt.Errorf("remove P2G guard prime after FoldToAggregate: %w", err)
	}
	if compact.Level() != adapter.baseMaxLevel {
		return nil, fmt.Errorf("guarded ingress consumed %d levels, want exactly one: output=%d baseMax=%d", level-compact.Level(), compact.Level(), adapter.baseMaxLevel)
	}
	if relative := math.Abs(compact.Scale-adapter.params.Scale()) / adapter.params.Scale(); relative > 1e-12 {
		return nil, fmt.Errorf("guarded ingress scale=%g, want Delta=%g (relative error=%g)", compact.Scale, adapter.params.Scale(), relative)
	}
	adapter.requireCompact("owner ingress output", compact)
	adapter.counts.owners++
	adapter.counts.guardedFolds++
	adapter.counts.guardRescales++
	return compact, nil
}

