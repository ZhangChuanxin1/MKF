// These identifiers are intentionally disjoint from
// paperMKFCKKSConstructionID and the frozen legacy CPU result identity.
// P2G appends one guard prime to P2 only for fresh owner ingress.
const (
	guardedCompactMKFCKKSConstructionID = "MKF-CKKS-P2G-guarded-fold-once+permanent-aggregate-rq2-v1"
	guardedCompactP2GParameterID        = "P2G"
	guardedCompactFoldKeyGenMode        = "distributed_public_ckg_plus_party_pke"
	guardedCompactTimingWarmups         = 0
	guardedCompactTimingTrials          = 10
)

func guardedCompactResNet20ConstructionFor(parameter string) string {
	if parameter == guardedCompactP2GN16ParameterID {
		return guardedCompactP2GN16CPUConstructionID
	}
	return guardedCompactMKFCKKSConstructionID
}

// guardedCompactTimingBoundary freezes the intended future measurement
// boundary without launching a benchmark. Fresh sparse owner ciphertexts and
// all keys must be staged before the timer. The timed region begins with each
// public guarded fold/rescale and contains all network evaluation and 22
// collective refresh protocols. Decryption, plaintext oracles, validation,
// and result serialization remain outside it.
type guardedCompactTimingBoundary struct {
	Warmups                    int
	Trials                     int
	StageSparseOwnerInputs     bool
	IncludeGuardedIngress      bool
	IncludeNetworkEvaluation   bool
	IncludeCollectiveRefresh   bool
	ExcludeKeyGeneration       bool
	ExcludeEncryption          bool
	ExcludeCorrectnessOracle   bool
	ExcludeResultSerialization bool
}

var guardedCompactFutureTimingBoundary = guardedCompactTimingBoundary{
	Warmups: guardedCompactTimingWarmups, Trials: guardedCompactTimingTrials,
	StageSparseOwnerInputs: true, IncludeGuardedIngress: true, IncludeNetworkEvaluation: true,
	IncludeCollectiveRefresh: true, ExcludeKeyGeneration: true, ExcludeEncryption: true,
	ExcludeCorrectnessOracle: true, ExcludeResultSerialization: true,
}

// guardedCompactMKFCounts are structural, never timing, counters. In
// particular, networkProducts excludes the ciphertext multiplications used
// internally by Lattigo's degree-59 polynomial evaluator.
type guardedCompactMKFCounts struct {
	owners             int
	guardedFolds       int
	guardRescales      int
	networkProducts    int
	polynomialProducts int
	rotations          int
	polynomials        int
	refreshes          int
}

